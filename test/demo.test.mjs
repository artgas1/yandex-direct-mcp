import { strict as assert } from 'node:assert';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';

/**
 * Сторож записи в README.
 *
 * Картинка в README показывает три превращения, и она статична — если сервер
 * перестанет их делать, картинка останется прежней и соврёт. Здесь тот же
 * прогон выполняется по-настоящему, и утверждения проверяются на его выводе.
 *
 * Прогон без сети и без токена: демо поднимает собственную заглушку.
 */
const DEMO = fileURLToPath(new URL('../tools/demo.mjs', import.meta.url));

const output = execFileSync(process.execPath, [DEMO], {
  encoding: 'utf8',
  timeout: 60_000,
  // Цвета мешают сравнению, а сама раскраска к утверждениям отношения не имеет.
  env: { ...process.env, NO_COLOR: '1' },
}).replace(/\[[0-9;]*m/g, '');

test('демо вообще отработало', () => {
  assert.match(output, /direct_campaigns_get/);
});

test('деньги в записи действительно пересчитаны', () => {
  // Слева микро-единицы, справа валюта счёта. Если пересчёт сломается,
  // справа окажется то же самое число, и тест упадёт.
  assert.match(output, /1000000000/, 'слева обязана быть исходная микро-единица');
  assert.match(output, /\b1000\b/, 'справа обязан быть пересчёт');
});

test('идентификатор в записи слева испорчен, справа цел', () => {
  // Ровно то, ради чего написан json.ts. Обе формы должны присутствовать
  // одновременно — иначе картинка перестанет доказывать то, что обещает.
  assert.match(output, /1234567890123456800/, 'голый разбор обязан испортить');
  assert.match(output, /"1234567890123456789"/, 'сервер обязан сохранить точно');
  assert.match(output, /слева испорчен разбором/);
});

test('обёртка Items в записи развёрнута', () => {
  assert.match(output, /\{"Items":\[…\]\}/);
  assert.match(output, /\["бесплатно","отзывы"\]/);
});

test('отказ с кодом 202 в записи распознан отказом', () => {
  // Отрицательный контроль ко всей затее: реализация, доверяющая статусу,
  // показала бы здесь успех.
  assert.match(output, /отказ с HTTP 202/);
  assert.match(output, /Директ отказал: код 55/);
});
