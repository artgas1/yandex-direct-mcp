/**
 * Разбор ответов Директа без потери точности.
 *
 * Зачем отдельный модуль. Идентификаторы объявлений в Директе не помещаются в
 * число JavaScript: схема объявляет их типом `xsd:long`, и на живых кабинетах
 * встречаются девятнадцатизначные (проверено прогоном живого API на двух).
 * `JSON.parse` держит ровно 9007199254740991, то есть шестнадцать цифр: скажем,
 * 1234567890123456789 он превращает в 1234567890123456800.
 *
 * Опасен здесь не сам сдвиг, а то, каким он выходит наружу. Испорченный
 * идентификатор — по-прежнему правдоподобное число, никакой ошибки не возникает,
 * и запрос с ним Директ принимает: HTTP 200 и тело `{"result":{}}`. То есть
 * сервер на голом `JSON.parse` не падает и не жалуется — он сообщает «такого
 * объявления нет». Пустота как доказательство отсутствия: ровно тот ответ,
 * который выглядит нормально и потому не перепроверяется.
 *
 * Решение выбрано не арифметическое, а представлением, и оно опирается на
 * отдельно снятый факт: Директ принимает идентификатор строкой наравне с числом
 * (проверено тем же прогоном — запрос с `Ids` в виде строк вернул то же
 * объявление). Значит длинное целое можно держать строкой на всём пути: оно
 * приходит точным, показывается точным и уходит обратно точным. Обратного
 * преобразования не нужно нигде.
 */

/** Предел, выше которого целое перестаёт быть представимым точно. */
export const SAFE_MAX = BigInt(Number.MAX_SAFE_INTEGER);
const SAFE_MIN = -SAFE_MAX;

/** Столько цифр помещается заведомо — ниже этого BigInt можно не звать. */
const ALWAYS_SAFE_DIGITS = 15;

/** Целое из текста JSON, которое не переживёт разбор числом. */
export function exceedsSafeRange(raw: string): boolean {
  const digits = raw.startsWith('-') ? raw.length - 1 : raw.length;
  if (digits <= ALWAYS_SAFE_DIGITS) return false;
  const value = BigInt(raw);
  return value > SAFE_MAX || value < SAFE_MIN;
}

/**
 * Заключает в кавычки те целые, которые иначе потеряют точность.
 *
 * Работа идёт по тексту, а не по разобранному дереву, и иначе нельзя:
 * `JSON.parse` с reviver получает УЖЕ испорченное число, восстанавливать там
 * нечего. Сканер отслеживает, находимся ли мы внутри строкового литерала, —
 * цифры внутри названия кампании трогать нельзя.
 */
export function quoteUnsafeIntegers(text: string): string {
  let out = '';
  let i = 0;
  let inString = false;

  while (i < text.length) {
    const ch = text[i];

    if (inString) {
      if (ch === '\\') {
        out += ch + (text[i + 1] ?? '');
        i += 2;
        continue;
      }
      if (ch === '"') inString = false;
      out += ch;
      i++;
      continue;
    }

    if (ch === '"') {
      inString = true;
      out += ch;
      i++;
      continue;
    }

    // Вне строки минус и цифра могут начинать только число.
    if (ch === '-' || (ch >= '0' && ch <= '9')) {
      let j = i;
      if (text[j] === '-') j++;
      const firstDigit = j;
      while (j < text.length && text[j] >= '0' && text[j] <= '9') j++;

      const hasDigits = j > firstDigit;
      const next = text[j];
      // Дробное и экспоненциальное оставляем числами: точность там и так
      // приблизительная, а строкой они сломают арифметику потребителя.
      const isInteger = hasDigits && next !== '.' && next !== 'e' && next !== 'E';
      const raw = text.slice(i, j);

      out += isInteger && exceedsSafeRange(raw) ? `"${raw}"` : raw;
      i = j;
      continue;
    }

    out += ch;
    i++;
  }

  return out;
}

/**
 * Разбор тела ответа. Отличается от `JSON.parse` ровно одним: длинные целые
 * приезжают строками, а не искажёнными числами.
 */
export function parseExact(text: string): unknown {
  return JSON.parse(quoteUnsafeIntegers(text));
}
